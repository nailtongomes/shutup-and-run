//! The output of each job, kept on this machine for its owner and for an
//! agent to read later: the last 256 KiB of stdout and stderr, one file per
//! job next to the history (`<history dir>/logs/<job id>.log`), written just
//! before the container is removed. Files older than 7 days are deleted.
//! Nothing is masked: a job that prints a secret leaves it here, readable by
//! root (on Windows, by whoever can run the distribution).

use std::io::Write;
use std::path::{Path, PathBuf};
use std::time::{Duration, SystemTime, UNIX_EPOCH};

/// The most of a job's output that is kept: its end.
pub const MAX_BYTES: usize = 256 * 1024;
/// Logs are deleted this long after they were written.
pub const KEEP_SECS: u64 = 7 * 86_400;

/// `<history dir>/logs`.
pub fn dir(history: &Path) -> PathBuf {
    history
        .parent()
        .filter(|p| !p.as_os_str().is_empty())
        .unwrap_or(Path::new("."))
        .join("logs")
}

/// Where the log of job `id` is, whether or not it exists. Job ids are
/// generated by the worker (`[0-9a-f-]`), so the name is safe as a path.
pub fn path(history: &Path, id: &str) -> PathBuf {
    dir(history).join(format!("{id}.log"))
}

/// The last `max` bytes of `bytes`. When something was cut, the partial
/// first line goes too, so the file starts at a line.
pub fn clip(bytes: &[u8], max: usize) -> &[u8] {
    if bytes.len() <= max {
        return bytes;
    }
    let tail = &bytes[bytes.len() - max..];
    match tail.iter().position(|b| *b == b'\n') {
        Some(at) if at + 1 < tail.len() => &tail[at + 1..],
        _ => tail,
    }
}

/// Write the log of job `id`: at most [`MAX_BYTES`], mode 600, through a
/// temporary file so a reader never sees half of one.
pub fn save(history: &Path, id: &str, output: &[u8]) -> std::io::Result<PathBuf> {
    let dir = dir(history);
    std::fs::create_dir_all(&dir)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(&dir, std::fs::Permissions::from_mode(0o700))?;
    }
    let target = path(history, id);
    let tmp = dir.join(format!("{id}.log.tmp"));
    let mut options = std::fs::OpenOptions::new();
    options.write(true).create(true).truncate(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        options.mode(0o600);
    }
    let mut file = options.open(&tmp)?;
    file.write_all(clip(output, MAX_BYTES))?;
    file.sync_all()?;
    drop(file);
    std::fs::rename(&tmp, &target)?;
    Ok(target)
}

/// A log on disk.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Info {
    pub path: PathBuf,
    pub bytes: u64,
    /// When it was written, in Unix seconds.
    pub written_at: i64,
}

pub fn info(history: &Path, id: &str) -> Option<Info> {
    let path = path(history, id);
    let meta = std::fs::metadata(&path).ok().filter(|m| m.is_file())?;
    Some(Info {
        bytes: meta.len(),
        written_at: unix(meta.modified().ok()?),
        path,
    })
}

/// The job ids that have a log, from the file names.
pub fn ids(history: &Path) -> Vec<String> {
    let Ok(entries) = std::fs::read_dir(dir(history)) else {
        return Vec::new();
    };
    entries
        .filter_map(|e| e.ok())
        .filter_map(|e| {
            e.file_name()
                .to_str()
                .and_then(|name| name.strip_suffix(".log"))
                .map(str::to_string)
        })
        .collect()
}

/// Delete the logs written more than [`KEEP_SECS`] before `now`, and a
/// temporary file a crash left. Returns how many went.
pub fn purge(history: &Path, now: SystemTime) -> usize {
    let Ok(entries) = std::fs::read_dir(dir(history)) else {
        return 0;
    };
    let keep = Duration::from_secs(KEEP_SECS);
    let mut removed = 0;
    for entry in entries.filter_map(|e| e.ok()) {
        let name = entry.file_name();
        let name = name.to_string_lossy();
        if !name.ends_with(".log") && !name.ends_with(".log.tmp") {
            continue;
        }
        let old = entry
            .metadata()
            .and_then(|m| m.modified())
            .ok()
            .and_then(|at| now.duration_since(at).ok())
            .is_some_and(|age| age > keep);
        if old && std::fs::remove_file(entry.path()).is_ok() {
            removed += 1;
        }
    }
    removed
}

/// The last `lines` lines of `text`.
pub fn tail_lines(text: &str, lines: usize) -> &str {
    if lines == 0 {
        return "";
    }
    let trimmed = text.strip_suffix('\n').unwrap_or(text);
    match trimmed.rmatch_indices('\n').nth(lines - 1) {
        Some((at, _)) => &text[at + 1..],
        None => text,
    }
}

fn unix(at: SystemTime) -> i64 {
    at.duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn history(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!(
            "shutup-and-run-joblogs-{name}-{}",
            std::process::id()
        ));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir.join("jobs.sqlite")
    }

    #[test]
    fn a_long_output_keeps_its_last_256_kib_from_a_line_start() {
        let line = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcde\n";
        let mut output = String::from("FIRST LINE\n");
        while output.len() < 3 * MAX_BYTES {
            output.push_str(line);
        }
        output.push_str("LAST LINE\n");
        let history = history("clip");
        let saved = save(&history, "job-1", output.as_bytes()).unwrap();
        let kept = std::fs::read(&saved).unwrap();
        assert!(kept.len() <= MAX_BYTES && kept.len() > MAX_BYTES - line.len());
        assert!(kept.ends_with(b"LAST LINE\n"));
        assert!(kept.starts_with(line.as_bytes()));
        assert!(!String::from_utf8_lossy(&kept).contains("FIRST LINE"));
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = std::fs::metadata(&saved).unwrap().permissions().mode() & 0o777;
            assert_eq!(mode, 0o600);
        }
        // A short one is kept whole.
        assert_eq!(clip(b"a\nb\n", MAX_BYTES), b"a\nb\n");
        assert_eq!(info(&history, "job-1").unwrap().bytes, kept.len() as u64);
        assert_eq!(ids(&history), vec!["job-1".to_string()]);
    }

    #[test]
    fn logs_older_than_seven_days_are_deleted_and_newer_ones_kept() {
        let history = history("purge");
        let old = save(&history, "old", b"old\n").unwrap();
        save(&history, "new", b"new\n").unwrap();
        let now = SystemTime::now();
        std::fs::File::options()
            .write(true)
            .open(&old)
            .unwrap()
            .set_modified(now - Duration::from_secs(KEEP_SECS + 60))
            .unwrap();
        assert_eq!(purge(&history, now), 1);
        assert!(!old.exists());
        assert!(info(&history, "new").is_some());
        assert_eq!(purge(&history, now), 0);
        // No folder yet is nothing to do.
        assert_eq!(purge(&self::history("none"), now), 0);
    }

    #[test]
    fn tail_takes_the_last_lines() {
        assert_eq!(tail_lines("a\nb\nc\n", 2), "b\nc\n");
        assert_eq!(tail_lines("a\nb\nc", 2), "b\nc");
        assert_eq!(tail_lines("a\nb\n", 5), "a\nb\n");
        assert_eq!(tail_lines("a\n", 0), "");
    }
}
